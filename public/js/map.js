function exportData(fmt) {
  const list = sorted(shown()), name = 'green-code-points-' + new Date().toISOString().slice(0, 10);
  const base = p => ({ id: p.id, title: p.title, title_en: p.title_en || '', type: p.type, governorate: p.gov, lat: p.lat, lng: p.lng, status: p.status || 'active', kind: p.kind, added: p.created_at || '', removed: p.removed_at || '', confirmations: p.confirms || 0, source: p.source || '' });
  let blob;
  if (fmt === 'csv') {
    const rows = list.map(base), cols = Object.keys(rows[0] || base({}));
    blob = new Blob(['﻿' + [cols.join(','), ...rows.map(r => cols.map(c => '"' + String(r[c] ?? '').replace(/"/g, '""') + '"').join(','))].join('\n')], { type: 'text/csv;charset=utf-8' });
  } else blob = new Blob([JSON.stringify({ type: 'FeatureCollection', features: list.map(p => ({ type: 'Feature', geometry: { type: 'Point', coordinates: [p.lng, p.lat] }, properties: base(p) })) })], { type: 'application/geo+json' });
  const a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = name + (fmt === 'csv' ? '.csv' : '.geojson'); document.body.appendChild(a); a.click(); setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 500);
}

